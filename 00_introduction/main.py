'''
Question 2:
Why is Python called an interpreted
and high-level programming language?
'''

# Python is an interpreted language,
# which means that its source code
# does not need to be compiled before execution.
#
# Python is also a high-level language,
# meaning that programmers do not need
# to know the internal details
# of the computer to write programs.

print("Python is an interpreted and high-level programming language.")

print("\n---------------------------------\n")

'''
Question 3:
Why is Python considered a
cross-platform and free language?
'''

# Python can run on many operating systems,
# including Windows, macOS, Linux,
# Android, and iOS.
#
# It is completely free,
# so it can be installed
# on as many computers as needed.

print("Python is cross-platform and free.")

print("\n---------------------------------\n")

'''
Question 4:
What does it mean that Python
is an object-oriented language?
'''

# Python allows programmers
# to create objects that represent
# real-world entities.
#
# For example, an object can represent
# a DNA molecule, a protein,
# an atom, a student,
# or even a car.
#
# Each object can have
# its own properties and behaviors.

print("Python is an object-oriented programming language.")

print("\n---------------------------------\n")

